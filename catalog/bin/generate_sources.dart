// ignore_for_file: depend_on_referenced_packages, avoid_print
import 'dart:convert';
import 'dart:io';
import 'package:path/path.dart' as p;

void main() {
  final currentDir = Directory.current.path;
  // Determine root directory of streaming_gen_ui package
  String rootPath = currentDir;
  if (p.basename(currentDir) == 'catalog') {
    rootPath = p.dirname(currentDir);
  }

  final registryDir = Directory(
    p.join(rootPath, 'lib', 'src', 'widgets', 'registries', 'core_registry'),
  );
  if (!registryDir.existsSync()) {
    print('Error: Core registry directory not found at ${registryDir.path}');
    exit(1);
  }

  final files = registryDir.listSync().whereType<File>().toList();
  final Map<String, String> sources = {};

  for (final file in files) {
    final name = p.basename(file.path);
    if (name.endsWith('.dart')) {
      final content = file.readAsStringSync();
      // Base64 encode to prevent any string escaping or multi-line syntax errors!
      final encoded = base64.encode(utf8.encode(content));
      sources[name] = encoded;
    }
  }

  // Generate widget_sources.g.dart
  final outputBuffer = StringBuffer();
  outputBuffer.writeln('// GENERATED CODE - DO NOT MODIFY BY HAND');
  outputBuffer.writeln('// Generated by catalog/bin/generate_sources.dart');
  outputBuffer.writeln();
  outputBuffer.writeln('const Map<String, String> widgetSources = {');

  sources.forEach((filename, encodedContent) {
    outputBuffer.writeln("  '$filename': '$encodedContent',");
  });

  outputBuffer.writeln('};');

  final outputDir = Directory(p.join(rootPath, 'catalog', 'lib', 'core'));
  if (!outputDir.existsSync()) {
    outputDir.createSync(recursive: true);
  }

  final outputFile = File(p.join(outputDir.path, 'widget_sources.g.dart'));
  outputFile.writeAsStringSync(outputBuffer.toString());
  print(
    'Successfully generated ${outputFile.path} with ${sources.length} sources.',
  );
}
